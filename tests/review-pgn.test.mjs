// ȘAH FĂRĂ FRONTIERE 15.0.0 — import PGN în analiză, deschideri recunoscute, revizuire cu greșeli etichetate și „Vezi poziția”.
// Rulare: node tests/review-pgn.test.mjs   (motor local, fără rețea)
import {launch, check, summary} from "./_lib.mjs";
const PANE = ".c1a-pane:not([hidden])";
const SPEECH = {content: "try{if(window.name!=='__sff_lang'){window.name='__sff_lang';localStorage.setItem('sah-fara-frontiere.lang','en')}}catch(e){}"};
const hub = async (page, n) => { if (!(await page.locator("dialog.c1a-dlg[open]").count())) await page.click("#table-btn"); await page.waitForSelector("dialog.c1a-dlg[open]"); await page.locator(".c1a-tab").nth(n).click(); await page.waitForTimeout(250); };
const {browser, page, st} = await launch({init: SPEECH});
await page.waitForTimeout(1000);
await hub(page, 1);
const PGN = `[Event "t"]\n[Result "0-1"]\n\n1. f3 {slab} e5 2. g4?? (2. e4) Qh4# 0-1`;
const ta = page.locator(`${PANE} textarea`);
check("câmp PGN prezent și etichetat", await ta.count() === 1 && await page.locator(`${PANE} label[for="${await ta.getAttribute("id")}"]`).count() === 1);
await ta.fill("1. e4 e5 2. Nf3 Nc6 3. Bb5 a6");
await page.locator(`${PANE} button`, {hasText: "Import PGN"}).click();
let out = await page.locator(`${PANE} .sh-anout`).innerText();
check("PGN valid încărcat și deschidere recunoscută (Ruy Lopez, Morphy)", /6 plies/.test(out) && /Ruy Lopez, Morphy Defence/.test(out), out);
const r1 = await page.evaluate(() => { const A = window.__sah8; return A.AN.G.game.moves.map(m => m.san).join(" "); });
check("mutările sunt în tablă", r1 === "e4 e5 Nf3 Nc6 Bb5 a6", r1);
await ta.fill("1. e4 e5 2. Ke3");
await page.locator(`${PANE} button`, {hasText: "Import PGN"}).click();
out = await page.locator(`${PANE} .sh-anout`).innerText();
check("mutare ilegală respinsă cu număr și text", /rejected/.test(out) && /Ke3/.test(out) && /no\. 3/.test(out), out);
await ta.fill("   ");
await page.locator(`${PANE} button`, {hasText: "Import PGN"}).click();
check("PGN gol: mesaj", /Paste a PGN/.test(await page.locator(`${PANE} .sh-anout`).innerText()));
await ta.fill("[FEN \"nu e fen\"]\n1. e4");
await page.locator(`${PANE} button`, {hasText: "Import PGN"}).click();
check("FEN invalid în PGN respins", /FEN in the PGN is invalid/.test(await page.locator(`${PANE} .sh-anout`).innerText()));
await ta.fill(PGN);
await page.locator(`${PANE} button`, {hasText: "Import PGN"}).click();
check("PGN cu etichete, comentarii, variante și rezultat acceptat", /4 plies/.test(await page.locator(`${PANE} .sh-anout`).innerText()));
await page.locator(`${PANE} button`, {hasText: "Analyse the game"}).click();
await page.waitForFunction(() => /Average loss/.test(document.querySelector(".c1a-pane:not([hidden]) .sh-anout").textContent), null, {timeout: 90000});
out = await page.locator(`${PANE} .sh-anout`).innerText();
check("revizuire: gafă etichetată, deschidere, pierdere medie", /blunder|mistake/.test(out) && /g4/.test(out) && /Bird|Nimzowitsch|Open|No opening|Opening recognised/.test(out) && /Average loss/.test(out), out);
const goBtns = page.locator(`${PANE} .sh-anout li button`);
check("fiecare greșeală are buton «Show position»", await goBtns.count() >= 1);
const full = await page.evaluate(() => window.__sah8.AN.G.game.moves.length);
await goBtns.first().click();
const j = await page.evaluate(() => ({n: window.__sah8.AN.G.game.moves.length, fen: window.__sah8.C.toFEN(window.__sah8.AN.G.game.pos)}));
check("poziția dinaintea greșelii e pe tablă", j.n < full && j.n >= 0, j);
check("mesaj cu mutarea mai bună", /Position before the move/.test(await page.locator(`${PANE} .c1a-note[role=status]`).innerText()));
await page.locator(`${PANE} button`, {hasText: "Back to the full game"}).click();
check("revenire la partida completă", (await page.evaluate(() => window.__sah8.AN.G.game.moves.length)) === full);
// deschidere necunoscută
await ta.fill("1. a3 a6");
await page.locator(`${PANE} button`, {hasText: "Import PGN"}).click();
check("fără potrivire: mesaj onest despre lista scurtă", /No opening in the built-in list/.test(await page.locator(`${PANE} .sh-anout`).innerText()));
check("fără erori în pagină", st.errs.length === 0, st.errs);
await browser.close(); summary();
